const assert=require('node:assert/strict');
const api=require('./distribution-core');
const calculated=api.calculateDistribution({partners:['A','B'],shares:{A:60,B:40},profit:1000,lossCarryForward:100,rewards:{A:50,B:50}});
assert.equal(calculated.baseForDistribution,800);
assert.deepEqual(calculated.rows,[{partner:'A',share:60,accrued:480},{partner:'B',share:40,accrued:320}]);
assert.equal(calculated.totalAccrued,900);
const pennies=api.calculateDistribution({partners:['A','B','C'],shares:{A:34,B:33,C:33},profit:0.01});
assert.equal(pennies.rows.reduce((sum,row)=>sum+row.accrued,0),0.01);
assert.equal(pennies.rows[0].accrued,0.01);
const loss=api.calculateDistribution({partners:['A'],shares:{A:100},profit:-500,rewards:{A:100}});
assert.equal(loss.baseForDistribution,0);assert.equal(loss.rows[0].accrued,0);assert.equal(loss.totalAccrued,0);
assert.equal(api.carryBefore([{status:'approved',periodEnd:'2026-01-31',profit:-500},{status:'approved',periodEnd:'2026-02-28',profit:200}],'2026-03-01'),300);
assert.deepEqual(api.unpaidPositions([{status:'approved',rows:[{partner:'A',accrued:500}],workRewards:{A:100}}],[{party:'A',value:250}],['A']),{A:350});
assert.deepEqual(api.proportionalPayments({A:1000,B:1000},600,{A:60,B:40}),{A:360,B:240});
assert.deepEqual(api.proportionalPayments({A:100,B:1000},600,{A:60,B:40}),{A:100,B:500});
const reserved=api.calculateDistribution({partners:['A','B'],shares:{A:60,B:40},profit:55000,reserve:16500});
assert.equal(reserved.baseForDistribution,38500);assert.deepEqual(reserved.rows.map(row=>row.accrued),[23100,15400]);
const withLoan=api.calculateDistribution({partners:['A','B'],shares:{A:60,B:40},profit:55000,reserve:16500,loanRepayments:{A:8000,B:0}});
assert.equal(withLoan.baseForDistribution,30500);assert.equal(withLoan.loanRepaymentTotal,8000);
console.log('distribution-core: assertions passed');

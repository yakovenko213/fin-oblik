const assert=require('node:assert/strict');
const planned=require('./planned-payments-core');
const accounting=require('./accounting-core');

const legacyTransactions=[{id:1,type:'income',value:1000,account:'A'},{id:2,type:'expense',value:250,account:'A'}];
const before={balance:legacyTransactions.reduce((sum,tx)=>sum+accounting.getSignedAmount(tx),0),profit:1000-250};
const migrated=planned.migrateState({transactions:legacyTransactions,journal:[],closedPeriods:[]});
assert.deepEqual(migrated.plannedPayments,[]);
assert.deepEqual(migrated.plannedSettings,{freezeEnabled:true,freezeHorizon:'next_month_end',horizonDays:30});
assert.deepEqual(migrated.transactions,legacyTransactions);
assert.deepEqual(before,{balance:750,profit:750});
assert.equal(migrated.transactions.reduce((sum,tx)=>sum+accounting.getSignedAmount(tx),0),before.balance);
assert.equal(planned.remainingAmount({amount:1000,paidAmount:275.55}),724.45);
assert.equal(planned.freezeThroughDate(planned.defaultSettings,'2026-10-17'),'2026-11-30');
assert.equal(planned.freezeThroughDate({freezeEnabled:true,freezeHorizon:'days',horizonDays:30},'2026-10-17'),'2026-11-16');
const payment=planned.createPayment({id:'p1',name:'Оренда',kind:'rent',account:'A',amount:1000,dueDate:'2026-11-01',status:'planned'});
assert.equal(payment.paidAmount,0);assert.equal(payment.isEstimate,false);assert.equal(payment.isDeleted,false);
assert.throws(()=>planned.createPayment({...payment,id:'p2',amount:0}),/amount/);
assert.throws(()=>planned.updateSettings(planned.defaultSettings,{freezeHorizon:'all'},'Менеджер'),/Власник/);
assert.equal(planned.updateSettings(planned.defaultSettings,{freezeHorizon:'days'},'Власник').freezeHorizon,'days');
assert.equal(planned.isInFreezeHorizon(payment,planned.defaultSettings,'2026-10-17'),true);
const rule={id:'r1',name:'Податок',basis:'income_percent',value:5,account:'A',payDay:20,active:true};
let tx=[{isoDate:'2026-09-10',type:'income',value:200000}];
let tax=planned.recalculateTaxPayments({rules:[rule],transactions:tx,payments:[],closedPeriods:[]});
assert.equal(tax.payments[0].amount,10000);assert.equal(tax.payments[0].dueDate,'2026-10-20');
tx.push({isoDate:'2026-09-20',type:'income',value:50000});tax=planned.recalculateTaxPayments({rules:[rule],transactions:tx,payments:tax.payments,closedPeriods:[]});

tax=planned.recalculateTaxPayments({rules:[rule],transactions:tx,payments:tax.payments,closedPeriods:[{start:'2026-09-01',end:'2026-09-30',status:'closed'}]});assert.equal(tax.payments[0].isEstimate,false);
tx.push({isoDate:'2026-09-25',type:'income',value:50000});tax=planned.recalculateTaxPayments({rules:[rule],transactions:tx,payments:tax.payments,closedPeriods:[{start:'2026-09-01',end:'2026-09-30',status:'closed'}]});assert.equal(tax.payments[0].amount,12500);
